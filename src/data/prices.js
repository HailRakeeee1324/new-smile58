function isSurgicalProcedure(value) {
  return /удаление (?:временного|постоянного|ретинированного|дистопированного|сверхкомплектного|зуба|имплантата|подвижной стенки)|резекц|цист|абсцесс|лоскутн|уздеч|синус-лифтинг|костная пластика|гингив|перикоронит|альвеоляр|вестибулопластика|кюретаж лунки|наложение шва/.test(value);
}

function inferRoute(name, fallback) {
  const value = name.toLowerCase();
  if (/имплант|синус-лифтинг|костная пластика/.test(value)) return routePaths.implantaciya;
  if (/гигиен|air flow|зубн(?:ых|ые) отложен|мягкого нал[её]та|фтор|фиссур|пародонт/.test(value)) return routePaths.gigiena;
  if (isSurgicalProcedure(value)) return routePaths.udalenieZubov;
  if (/винир/.test(value)) return routePaths.viniry;
  if (/корон|протез|оттиск|вкладк|wax-up|mock-up|кламмер|перебазиров/.test(value)) return routePaths.protezirovanie;
  if (/отбелив/.test(value)) return routePaths.otbelivanie;
  if (/кариес|пломб|канал|пульп|реставрац|восстанов/.test(value)) return routePaths.lechenieKariesa;
  return fallback;
}

function inferFilter(name, fallback) {
  const value = name.toLowerCase();
  if (/имплант|синус-лифтинг|костная пластика/.test(value)) return "implantation";
  if (/гигиен|air flow|зубн(?:ых|ые) отложен|мягкого нал[её]та|фтор|фиссур|пародонт/.test(value)) return "hygiene";
  if (isSurgicalProcedure(value)) return "surgery";
  if (/отбелив|скайс/.test(value)) return "aesthetics";
  if (/корон|протез|оттиск|вкладк|винир|wax-up|mock-up|кламмер|перебазиров/.test(value)) return "prosthetics";
  if (/консультац|при[её]м|анестез/.test(value)) return "consultation";
  return fallback;
}

